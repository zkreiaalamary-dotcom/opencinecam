def build_3d_cube(title: str, size: int, fn) -> bytes:
    """Adobe Cube 1.0 3D LUT in red-fastest order, LF line endings."""
    lines = [
        f'TITLE "{title}"',
        "# Technical color-space / transfer transform generated by tools/generate_cinema_luts.py",
        f"LUT_3D_SIZE {size}",
        "DOMAIN_MIN 0.0 0.0 0.0",
        "DOMAIN_MAX 1.0 1.0 1.0",
    ]
    grid = [i / (size - 1) for i in range(size)]
    for b in grid:
        for g in grid:
            for r in grid:
                out = cs.clamp_vec3(fn((r, g, b)), 0.0, 1.0)
                lines.append(f"{out[0]:.6f} {out[1]:.6f} {out[2]:.6f}")
    return ("\n".join(lines) + "\n").encode("utf-8")


def oclog2_hlg_to_rec709(rgb: cs.Vec3) -> cs.Vec3:
    # HLG-derived OCLog2 has 18% grey at 0.048133 scene linear -> scale by TIER_GREY_RATIO.
    lin_2020 = (cs.oclog2_decode(rgb[0]), cs.oclog2_decode(rgb[1]), cs.oclog2_decode(rgb[2]))
    lin_709 = cs.mat3_vec(cs.BT2020_TO_BT709, lin_2020)
    return cs.soft_tonemap_rec709(lin_709, gain=cs.TIER_GREY_RATIO, knee=0.5)


def oclog2_scene_to_rec709(rgb: cs.Vec3) -> cs.Vec3:
    lin_2020 = (cs.oclog2_decode(rgb[0]), cs.oclog2_decode(rgb[1]), cs.oclog2_decode(rgb[2]))
    lin_709 = cs.mat3_vec(cs.BT2020_TO_BT709, lin_2020)
    return cs.soft_tonemap_rec709(lin_709, gain=1.0, knee=0.5)


