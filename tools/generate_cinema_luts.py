def dctl_oclog3_transfer(inverse: bool) -> bytes:
    fn = "oclog3_decode" if inverse else "oclog3_encode"
    src = f"""/* SPDX-License-Identifier: Apache-2.0 */
// OpenCineCam OCLog3 v{cs.OCLOG3_CUT} {"inverse" if inverse else "forward"} (BT.2020 scene-linear [0, 16] <-> OCLog3 [0.095, 0.920])
__DEVICE__ float oclog3_encode(float x) {{
    x = _fmaxf(0.0f, _fminf(16.0f, x));
    if (x < {cs.OCLOG3_CUT:.15f}f) return {cs.OCLOG3_M:.15f}f * x + {cs.OCLOG3_BLACK:.6f}f;
    return {cs.OCLOG3_A_LN:.15f}f * _logf(x + {cs.OCLOG3_C:.15f}f) + {cs.OCLOG3_D:.15f}f;
}}
__DEVICE__ float oclog3_decode(float y) {{
    y = _fmaxf({cs.OCLOG3_BLACK:.6f}f, _fminf({cs.OCLOG3_WHITE:.6f}f, y));
    if (y < {cs.OCLOG3_CUT_CODE:.15f}f) return _fmaxf(0.0f, (y - {cs.OCLOG3_BLACK:.6f}f) / {cs.OCLOG3_M:.15f}f);
    return _fmaxf(0.0f, _fminf(16.0f, _expf((y - {cs.OCLOG3_D:.15f}f) / {cs.OCLOG3_A_LN:.15f}f) - {cs.OCLOG3_C:.15f}f));
}}
__DEVICE__ float3 transform(int p_Width, int p_Height, int p_X, int p_Y, float p_R, float p_G, float p_B) {{
    return make_float3({fn}(p_R), {fn}(p_G), {fn}(p_B));
}}
"""
    return src.encode("utf-8")


def dctl_to_working_space(log_ver: int, target: str) -> bytes:
    is_dwg = target == "dwg"
    mat = cs.BT2020_TO_DWG if is_dwg else cs.BT2020_TO_ACES_AP1
    decode_fn = (
        f"""__DEVICE__ float decode_log(float y) {{
    y = _clampf(y, 0.10f, 0.90f);
    return (_powf(51.0f, (y - 0.10f) / 0.80f) - 1.0f) / 50.0f;
}}"""
        if log_ver == 2
        else f"""__DEVICE__ float decode_log(float y) {{
    y = _clampf(y, {cs.OCLOG3_BLACK:.6f}f, {cs.OCLOG3_WHITE:.6f}f);
    if (y < {cs.OCLOG3_CUT_CODE:.15f}f) return _fmaxf(0.0f, (y - {cs.OCLOG3_BLACK:.6f}f) / {cs.OCLOG3_M:.15f}f);
    return _fmaxf(0.0f, _fminf(16.0f, _expf((y - {cs.OCLOG3_D:.15f}f) / {cs.OCLOG3_A_LN:.15f}f) - {cs.OCLOG3_C:.15f}f));
}}"""
    )
    encode_out = (
        """__DEVICE__ float encode_target(float x) {
    x = _fmaxf(0.0f, x);
    if (x <= 0.00262409f) return x * 10.44426855f;
    return (_log2f(x + 0.0075f) + 7.0f) * 0.07329248f;
}"""
        if is_dwg
        else """__DEVICE__ float encode_target(float x) {
    x = _fmaxf(0.0f, x);
    if (x <= 0.0078125f) return 10.5402377416545f * x + 0.0729055341958355f;
    return (_log2f(x) + 9.72f) / 17.52f;
}"""
    )
    src = f"""/* SPDX-License-Identifier: Apache-2.0 */
// OpenCineCam OCLog{log_ver} (BT.2020) to {"DaVinci Wide Gamut / Intermediate" if is_dwg else "ACEScct (AP1)"}
{decode_fn}
{encode_out}
__DEVICE__ float3 transform(int p_Width, int p_Height, int p_X, int p_Y, float p_R, float p_G, float p_B) {{
    float lr = decode_log(p_R);
    float lg = decode_log(p_G);
    float lb = decode_log(p_B);
    float tr = {mat[0][0]:.9f}f * lr + {mat[0][1]:.9f}f * lg + {mat[0][2]:.9f}f * lb;
    float tg = {mat[1][0]:.9f}f * lr + {mat[1][1]:.9f}f * lg + {mat[1][2]:.9f}f * lb;
    float tb = {mat[2][0]:.9f}f * lr + {mat[2][1]:.9f}f * lg + {mat[2][2]:.9f}f * lb;
    return make_float3(encode_target(tr), encode_target(tg), encode_target(tb));
}}
"""
    return src.encode("utf-8")


def artifact_payloads() -> dict[str, bytes]:
    return {
        "technical/OCLog2_BT2020_HLG_to_Rec709_33.cube": build_3d_cube("OCLog2 HLG-Grey-Aligned to Rec709 (33)", 33, oclog2_hlg_to_rec709),
        "technical/OCLog2_BT2020_Scene_to_Rec709_33.cube": build_3d_cube("OCLog2 Scene 0.18 to Rec709 (33)", 33, oclog2_scene_to_rec709),
        "technical/OCLog2_BT2020_to_DWG_Intermediate_33.cube": build_3d_cube("OCLog2 BT2020 to DaVinci Intermediate (33)", 33, oclog2_to_dwg),
        "technical/OCLog2_BT2020_to_ACEScct_33.cube": build_3d_cube("OCLog2 BT2020 to ACEScct AP1 (33)", 33, oclog2_to_acescct),
        "technical/OCLog3_BT2020_to_Rec709_33.cube": build_3d_cube("OCLog3 BT2020 to Rec709 (33)", 33, oclog3_to_rec709),
        "technical/OCLog3_BT2020_to_DWG_Intermediate_33.cube": build_3d_cube("OCLog3 BT2020 to DaVinci Intermediate (33)", 33, oclog3_to_dwg),
        "technical/OCLog3_BT2020_to_ACEScct_33.cube": build_3d_cube("OCLog3 BT2020 to ACEScct AP1 (33)", 33, oclog3_to_acescct),
        "dctl/oclog3-v1.dctl": dctl_oclog3_transfer(False),
        "dctl/oclog3-v1-inverse.dctl": dctl_oclog3_transfer(True),
        "dctl/oclog3-to-dwg-intermediate.dctl": dctl_to_working_space(3, "dwg"),
        "dctl/oclog3-to-acescct.dctl": dctl_to_working_space(3, "acescct"),
        "dctl/oclog2-to-dwg-intermediate.dctl": dctl_to_working_space(2, "dwg"),
        "dctl/oclog2-to-acescct.dctl": dctl_to_working_space(2, "acescct"),
    }


def generate(output: Path) -> dict[str, object]:
    payloads = artifact_payloads()
    for rel, data in payloads.items():
        target = output / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    manifest = {
        "schema": "opencinecam-cinema-luts-v1",
        "artifacts": {
            rel: {"sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)}
            for rel, data in sorted(payloads.items())
        },
    }
    (output / "manifest.json").write_bytes((json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8"))
    return manifest


def check(output: Path) -> bool:
    manifest_path = output / "manifest.json"
    if not manifest_path.is_file():
        return False
    payloads = artifact_payloads()
    for rel, data in payloads.items():
        target = output / rel
        if not target.is_file():
            return False
        if target.read_bytes().replace(b"\r\n", b"\n") != data:
            return False
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        ok = check(args.output)
        print(json.dumps({"output": str(args.output), "status": "PASS" if ok else "MISMATCH"}))
        return 0 if ok else 1
    manifest = generate(args.output)
    print(json.dumps({"output": str(args.output), "count": len(manifest["artifacts"])}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
